/** A 1x1 transparent GIF, followed by every byte value to check binary transfer. */
const GIF = [
  0x47, 0x49, 0x46, 0x38, 0x39, 0x61, 0x01, 0x00, 0x01, 0x00, 0x80, 0x00, 0x00, 0x00, 0x00, 0x00, 0xff, 0xff, 0xff,
  0x21, 0xf9, 0x04, 0x01, 0x00, 0x00, 0x00, 0x00, 0x2c, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00, 0x02,
  0x02, 0x44, 0x01, 0x00, 0x3b,
];

export function GET() {
  const bytes = new Uint8Array(GIF.length + 256);
  bytes.set(GIF);
  for (let i = 0; i < 256; i++) bytes[GIF.length + i] = i;
  return new Response(bytes, { headers: { "content-type": "image/gif", "cache-control": "public, max-age=60" } });
}
