//! Generates the typed TypeScript client (`@volt/api`) from registered actions and loaders.

use std::path::Path;

use serde::{Deserialize, Serialize};

use crate::registry;
use crate::router::RoutePattern;
use crate::types::{TypeScript, camel_case};

pub const SDK_FILE: &str = "api.ts";
pub const SERVER_INFO_FILE: &str = "server.json";

/// What the server exposes, consumed by the CLI to decide what can be prerendered.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ServerInfo {
    pub actions: Vec<String>,
    pub loaders: Vec<String>,
    pub api: Vec<String>,
}

pub struct Sdk {
    source: String,
    info: ServerInfo,
}

impl Sdk {
    pub fn generate() -> Self {
        let mut ts = TypeScript::new();
        let mut actions: Vec<_> = registry::actions().collect();
        actions.sort_by_key(|a| a.name);
        let mut loaders: Vec<_> = registry::loaders().collect();
        loaders.sort_by_key(|l| l.route);

        let action_lines: Vec<String> = actions
            .iter()
            .map(|action| {
                let input = action.input.map(|d| d(&mut ts)).unwrap_or_else(|| "void".into());
                let output = (action.output)(&mut ts);
                format!(
                    "export const {} = createAction<{input}, {output}>({:?});",
                    camel_case(action.name),
                    action.name
                )
            })
            .collect();
        let loader_lines: Vec<String> = loaders
            .iter()
            .map(|loader| format!("  {:?}: {};", RoutePattern::parse(loader.route).as_str(), (loader.output)(&mut ts)))
            .collect();

        let mut source = String::from("// Generated by volt from your Rust server. Do not edit.\n");
        source.push_str("import { createAction } from \"volt-rs/actions\";\n");
        source.push_str("import type { PageProps as BasePageProps } from \"volt-rs\";\n\n");
        for decl in ts.declarations() {
            source.push_str(decl);
            source.push_str("\n\n");
        }
        for line in &action_lines {
            source.push_str(line);
            source.push('\n');
        }
        if !action_lines.is_empty() {
            source.push('\n');
        }
        source.push_str("export interface Loaders {\n");
        for line in &loader_lines {
            source.push_str(line);
            source.push('\n');
        }
        source.push_str("}\n\n");
        source.push_str(
            "export type PageProps<R extends string = string> = BasePageProps<R extends keyof Loaders ? Loaders[R] : undefined>;\n",
        );

        let info = ServerInfo {
            actions: actions.iter().map(|a| a.name.to_owned()).collect(),
            loaders: loaders.iter().map(|l| RoutePattern::parse(l.route).as_str().to_owned()).collect(),
            api: registry::apis().map(|a| format!("{} {}", a.method, a.path)).collect(),
        };
        Self { source, info }
    }

    pub fn source(&self) -> &str {
        &self.source
    }

    pub fn info(&self) -> &ServerInfo {
        &self.info
    }

    /// Writes `api.ts` and `server.json`, skipping unchanged files to keep watchers quiet.
    pub fn write(&self, dir: &Path) -> std::io::Result<()> {
        std::fs::create_dir_all(dir)?;
        let info = serde_json::to_string_pretty(&self.info).map_err(std::io::Error::other)?;
        write_if_changed(&dir.join(SDK_FILE), &self.source)?;
        write_if_changed(&dir.join(SERVER_INFO_FILE), &info)
    }
}

pub fn write_if_changed(path: &Path, contents: &str) -> std::io::Result<()> {
    if std::fs::read_to_string(path).is_ok_and(|current| current == contents) {
        return Ok(());
    }
    std::fs::write(path, contents)
}
